"""Exact-score short Metropolis chains, M-R2 <=42/D<=2, optional QZ/ZQ occupancy.

Uses the scorer generated by explore_untoned_2121_v51.py as a persistent
evaluation service. Each accepted step records its parent and physical move.
"""
import argparse
import base64
import copy
import gzip
import gc
import hashlib
import json
import math
from pathlib import Path
import random
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--source-tag', required=True)
parser.add_argument('--seed-id', required=True)
parser.add_argument('--tag', required=True)
parser.add_argument('--steps', type=int, default=48)
parser.add_argument('--random-seed', type=int, default=1411)
parser.add_argument('--nh-ablation', action='store_true', help='Evaluate NH group, u/an alone, and their combination from the seed')
args = parser.parse_args()
sys.path.insert(0, str(ROOT / 'research/.cache/R11_integrated_replay'))
from memory_r2 import audit
from audit import split
from macroxue.engine import evaluate

cache = ROOT / 'research/.cache' / args.tag
cache.mkdir(parents=True, exist_ok=True)
source_cache = ROOT / 'research/.cache' / args.source_tag
html = (ROOT / 'a7_CKT_R11.html').read_text(encoding='utf-8')
data = json.loads(gzip.decompress(base64.b64decode(re.search(r'<script id="payload"[^>]*>([^<]+)', html)[1])))
entries = json.loads((source_cache / 'candidates.json').read_text())
seed = next(e for e in entries if e['id'] == args.seed_id)
scores = json.loads((ROOT / f'research/notes/2026-11-14-{args.source_tag}-neighbors.json').read_text())['results']
seed_score = next(e['score'] for e in scores if e['id'] == args.seed_id)
corpus = json.loads((ROOT / 'research/.cache/R11_integrated_replay/R9_corpora.json').read_text(encoding='utf-8'))['daily']['tokens']
indices = {py: i for i, py in enumerate(data['pinyin'])}
html_hash = hashlib.sha256(html.encode()).hexdigest()
data = {k:data[k] for k in ['pinyin','base']}
del html, entries
gc.collect()
source = (source_cache / 'score.js').read_text()
source = source[:source.index('  const candidates =')] + r'''
  const rl=require('node:readline').createInterface({input:process.stdin});
  for await(const line of rl) {
    const e=JSON.parse(line);
    const modes=Object.fromEntries(['keytao','sanpin'].map(mode=>[mode,evaluateV51ReferenceMode(e,mode,policy[mode])]));
    process.stdout.write(JSON.stringify({score:normalizedScore(modes,reference)})+'\n');
  }
}
main().catch(e=>{console.error(e);process.exit(1)});
'''
source = source.replace('function main() {', 'async function main() {')
(cache / 'service.js').write_text(source)
proc = subprocess.Popen(['node', str(cache / 'service.js'), '--id', 'QZ-e8f37a0998f9', '--html', str(ROOT / 'a7_CKT_R11.html'), '--snow', 'D:/C2D/Documents/rime-snow-pinyin', '--output', 'unused'], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, encoding='utf-8')
def score(e):
    proc.stdin.write(json.dumps(e) + '\n')
    proc.stdin.flush()
    line = proc.stdout.readline()
    if not line: raise RuntimeError('scoring service terminated')
    return json.loads(line)['score']

def prepare(e):
    for i, py in enumerate(data['pinyin']):
        if e['codeList'][i]:
            h, r = split(py, e['initialMap']['Y'] != e['initialMap']['YU'])
            e['codeList'][i] = e['initialMap'][h] + e['finalMap']['ve' if r == 'ue' else r]
    codes = [e['codeList'][p] for p, _ in data['base']]
    if [len({c[i] for c in codes}) for i in (0, 1)] != [21, 21]: return False
    if any(set(c) & set(e['tone']) for c in codes): return False
    a = audit(data, e)
    if a['M'] > 42 or a['ordinaryDisplacedCount'] > 2 or a['branchCount']: return False
    e['audit'] = {k:a[k] for k in ['M','ordinaryDisplacedCount','coverage','unique','branchCount']}
    e['audit'].update(qzEmpty='QZ' not in codes,zqEmpty='ZQ' not in codes)
    return True

def compact(e, value, **extras):
    strokes = ''.join(t.get('key') or e['codeList'][indices[t['pinyin']]].lower() for t in corpus)
    total = sum(w for _, w in data['base'])
    home = sum(w * sum(k in 'ASDFGHJKL' for k in e['codeList'][p]) / 2 for p,w in data['base'])/total
    return dict(id=e['id'],mutation=e.get('mutation'),initialMap=e['initialMap'],finalMap=e['finalMap'],audit=e['audit'],score=value,movingHand=evaluate(strokes,len(corpus))['score'],proxy={'home':home},**extras)

try:
    assert abs(score(seed)-seed_score)<1e-10
    prepare(seed)
    rng = random.Random(args.random_seed)
    current, current_score = seed, seed_score
    report = {'contract':'M-R2<=42,D<=2,21x21,no branches,fixed IVUAO; QZ/ZQ occupancy allowed; no home gate', 'sourceTag':args.source_tag,'sourceId':args.seed_id,'randomSeed':args.random_seed,'steps':args.steps,'htmlSha256':html_hash,'results':[compact(seed,seed_score,accepted=True)]}
    saved = [seed]
    seen = {tuple(seed['codeList'])}
    for step in range(args.steps):
        if args.nh_ablation and step >= 3: break
        for attempt in range(10000):
            e = copy.deepcopy(current)
            if args.nh_ablation:
                e = copy.deepcopy(seed)
                if step in (0,2):
                    e['finalMap'] = {k:'H' if v=='N' else 'N' if v=='H' else v for k,v in e['finalMap'].items()}
                if step in (1,2):
                    e['finalMap']['u'],e['finalMap']['an']=e['finalMap']['an'],e['finalMap']['u']
                e['mutation']=['NH whole-group','u/an only','NH whole-group then u/an'][step]
                if not prepare(e): raise RuntimeError('illegal ablation')
                break
            field = 'initialMap' if rng.random()<.2 else 'finalMap'
            a,b = rng.sample(list(e[field]),2)
            ka,kb = e[field][a],e[field][b]
            if ka==kb: continue
            group = rng.random()<.25
            if group:
                e[field] = {k:kb if v==ka else ka if v==kb else v for k,v in e[field].items()}
            else: e[field][a],e[field][b]=kb,ka
            e['mutation']=f'{field}:{"group " if group else ""}{a}({ka})<->{b}({kb})'
            if not prepare(e) or tuple(e['codeList']) in seen: continue
            break
        else: break
        seen.add(tuple(e['codeList']))
        e['id']=f'A{step:04}'
        value=score(e)
        temperature=.025*(.002/.025)**(step/max(1,args.steps-1))
        accepted=value<=current_score or rng.random()<math.exp(min(0,(current_score-value)/temperature))
        report['results'].append(compact(e,value,accepted=accepted,parent=seed['id'] if args.nh_ablation else current['id'],temperature=temperature,ablation=args.nh_ablation))
        saved.append(e)
        if accepted: current,current_score=e,value
        (cache/'candidates.json').write_text(json.dumps(saved))
        (ROOT/f'research/notes/2026-11-14-{args.tag}-neighbors.json').write_text(json.dumps(report,indent=2))
        print(json.dumps({'step':step,'mutation':e['mutation'],'score':value,'accepted':accepted,'qzEmpty':e['audit']['qzEmpty'],'zqEmpty':e['audit']['zqEmpty']}),flush=True)
    report['completed']=True
    (ROOT/f'research/notes/2026-11-14-{args.tag}-neighbors.json').write_text(json.dumps(report,indent=2))
finally:
    proc.stdin.close()
    proc.wait()
