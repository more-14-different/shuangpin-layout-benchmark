def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--html', type=Path, default=ROOT / 'a7_CKT_R11.html')
    parser.add_argument('--scores', type=Path, required=True)
    args = parser.parse_args()
    html_path = args.html.resolve()
    raw_html = html_path.read_bytes()
    text = raw_html.decode('utf-8')
    scores = json.loads(args.scores.read_text(encoding='utf-8'))
    if scores['version'] != 'B-completion-CKT-v0':
        raise ValueError('unexpected score version')
    match = PAYLOAD.search(text)
    if not match:
        raise ValueError('offline payload missing')
    data = json.loads(gzip.decompress(base64.b64decode(match[2])))
    ids = {entry['id'] for entry in data['entries']}
    if ids != set(scores['schemes']) or len(ids) != 562:
        raise ValueError('score records do not match all 562 page entries')
    normalized_auxiliary = 0
    for entry in data['entries']:
        keys = ''.join(sorted(set(entry.get('reservedKeys') or entry.get('tone') or '')))
        expected = {'AEIOU': 'AEUIO', 'AIOUV': 'AVUIO'}.get(keys)
        if expected and entry.get('auxiliaryClass') and entry['auxiliaryClass'] != expected:
            entry['auxiliaryClass'] = expected
            normalized_auxiliary += 1
    if 'completionB' not in data and hashlib.sha256(raw_html).hexdigest() != scores['source']['htmlSha256']:
        raise ValueError('HTML differs from the source used to score; recompute the scores first')
    if any(abs(delta) > 1e-10 for item in scores['schemes'].values()
           for delta in (item.get('bPathDeltas') or {}).values()):
        raise ValueError('B path audit mismatch')
    data['completionB'] = scores
    data['completionB']['ensembleDefinition'] = {
        'version': 'A7E-v7-B-completion-v0', 'referenceId': 'S005', 'beta': 4,
        'tracks': ['keytao.character', 'sanpin.character', 'keytao.word', 'sanpin.word'],
        'trackWeight': 0.25, 'tauDefaultMs': 150,
        'formula': '10 * [mean_4(((completionUpperMs + tau*p2) / (S005 completionUpperMs + tau*S005 p2))^4)]^(1/4)',
        'mix': 'q=0.5 word-token probability; ms/hanzi=(Tchar+Tword)/3; speed=60000/(ms/hanzi)',
        'excludes': ['M', 'D', 'V', 'P', 'home', 'commit', 'inter-item boundary'],
    }
    data['completionB']['compositeDefinition'] = {
        'version': 'B-completion-CKT-word2-v1', 'referenceId': 'S005', 'beta': 4,
        'characterWordTokenRatio': '1:2', 'trackWeights': {
            'keytao.character': 1 / 6, 'sanpin.character': 1 / 6,
            'keytao.word': 1 / 3, 'sanpin.word': 1 / 3,
        }, 'tauDefaultMs': 150,
        'formula': '10 * [(sum_char(ratio(tau)^4)/6) + (sum_word(ratio(tau)^4)/3)]^(1/4)',
        'time': 'completionUpperMs + tau*p2; S005 track as denominator at same tau',
    }
    reference = scores['schemes']['S005']['modes']
    data['completionB']['ensembleScores'] = {
        ident: {
            'equal': {str(tau): score_ensemble(row['modes'], reference, tau, 1)
                      for tau in (0, 150, 300, 600)},
            'word2': {str(tau): score_ensemble(row['modes'], reference, tau, 2)
                      for tau in (0, 150, 300, 600)},
        }
        for ident, row in scores['schemes'].items()
    }
    blob = base64.b64encode(gzip.compress(json.dumps(data, ensure_ascii=False, separators=(',', ':')).encode('utf-8'), mtime=0)).decode('ascii')
    text = text[:match.start(2)] + blob + text[match.end(2):]
    if MARKER in text:
        text, n = re.subn(re.escape(MARKER) + r'.*?(?=function uxRenderFair_legacy_unused\(\)\{)',
                          lambda _: FAIR_JS, text, count=1, flags=re.S)
        if n != 1:
            raise ValueError('existing fair table marker missing')
        text, n = re.subn(re.escape(GLOSSARY_MARKER) + r'.*?(?=const UX_SOURCE=\{)',
                          lambda _: GLOSSARY + '\n', text, count=1, flags=re.S)
        if n != 1:
            raise ValueError('existing glossary marker missing')
    else:
        text = replace_once(text, 'function uxRenderFair(){', FAIR_JS + 'function uxRenderFair_legacy_unused(){')
        text = replace_once(text, 'const UX_SOURCE={', GLOSSARY + '\nconst UX_SOURCE={')
        text = replace_once(text, "bench:'table',tau:'300'", "bench:'table',tau:'150'")
        text = replace_once(text, "UX.tau=s.tau||'300'", "UX.tau=s.tau||'150'")
        text = text.replace('</style>', CSS + '</style>', 1)
        text = replace_once(text, "'ensembleV5','fairCKT','audit'", "'ensembleV5','fairCKT','completionB','audit'")
        text = replace_once(text, "['CKT-X34','ckt'],['消歧补全','completion']", "['CKT-X34','ckt'],['A7E-v7','bV7'],['综合补全CKT','bComposite0'],['消歧补全','completion']")
        text = replace_once(text, "let vers=['ensemble','ensembleV2','ensembleV3','ensembleV4','ensembleV5'].map((k,i)=>[uxTerm('v'+(i+1),'A7E-v'+(i+1)),Object.keys(D[k]?.values||{}).length,esc(D[k]?.version||''),esc(D[k]?.referenceStateCount??D[k]?.referenceIds?.length??D[k]?.referencePopulation?.length??'见定义')]);",
            "let vers=['ensemble','ensembleV2','ensembleV3','ensembleV4','ensembleV5'].map((k,i)=>[uxTerm('v'+(i+1),'A7E-v'+(i+1)),Object.keys(D[k]?.values||{}).length,esc(D[k]?.version||''),esc(D[k]?.referenceStateCount??D[k]?.referenceIds?.length??D[k]?.referencePopulation?.length??'见定义')]);vers.push([uxTerm('v6','A7E-v6'),Object.keys(D.ensembleV6?.values||{}).length,esc(D.ensembleV6?.version||''),'S005固定锚点'],[uxTerm('bV7','A7E-v7-B补全'),Object.keys(D.completionB?.schemes||{}).length,esc(D.completionB?.ensembleDefinition?.version||''),'S005固定锚点·四组等权']);")
    if "[uxTerm('bComposite0','综合补全CKT（字:词=1:2）')" not in text:
        text = replace_once(
            text,
            "[uxTerm('bV7','A7E-v7-B补全'),Object.keys(D.completionB?.schemes||{}).length,esc(D.completionB?.ensembleDefinition?.version||''),'S005固定锚点·四组等权']",
            "[uxTerm('bV7','A7E-v7-B补全'),Object.keys(D.completionB?.schemes||{}).length,esc(D.completionB?.ensembleDefinition?.version||''),'S005固定锚点·四组等权'],[uxTerm('bComposite0','综合补全CKT（字:词=1:2）'),Object.keys(D.completionB?.ensembleScores||{}).length,esc(D.completionB?.compositeDefinition?.version||''),'S005固定锚点·同τ·单字1/3·二字词2/3']",
        )
    html_path.write_text(text, encoding='utf-8', newline='')
    print(json.dumps({'html': str(html_path), 'entries': len(ids), 'scoreVersion': scores['version'],
                      'normalizedAuxiliary': normalized_auxiliary,
                      'payloadBytes': len(blob), 'htmlBytes': html_path.stat().st_size}, ensure_ascii=False))


if __name__ == '__main__':
    main()
