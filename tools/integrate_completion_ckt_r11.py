def replace_once(text: str, old: str, new: str) -> str:
    n = text.count(old)
    if n != 1:
        raise ValueError(f'expected one replacement anchor, found {n}: {old[:80]}')
    return text.replace(old, new, 1)


def score_ensemble(modes: dict, reference: dict, tau: float, word_weight: float) -> float:
    total = 0.0
    for mode in ('keytao', 'sanpin'):
        for kind in ('character', 'word'):
            item = modes[mode][kind]
            base = reference[mode][kind]
            weighted_ms = item['completionUpperMs'] + tau * item['p2']
            base_ms = base['completionUpperMs'] + tau * base['p2']
            if not (math.isfinite(weighted_ms) and weighted_ms > 0 and math.isfinite(base_ms) and base_ms > 0):
                raise ValueError('invalid path time for ensemble')
            total += (word_weight if kind == 'word' else 1) * (weighted_ms / base_ms) ** 4
    return 10 * (total / (2 + 2 * word_weight)) ** .25


